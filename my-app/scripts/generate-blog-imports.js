import { readdirSync, writeFileSync } from "fs";
import { resolve, join } from "path";
import { fileURLToPath } from "url";

const __dirname = fileURLToPath(new URL(".", import.meta.url));
const blogPostsDir = resolve(__dirname, "../app/blog-posts");
const outputFile = resolve(__dirname, "../app/utils/blog-imports.generated.ts");

// Get all markdown files
const files = readdirSync(blogPostsDir)
  .filter((file) => file.endsWith(".md"))
  .sort();

// Generate imports and mapping
const imports = files.map((file, index) => {
  const varName = `post${index}`;
  const slug = file.replace(".md", "").toLowerCase().replace(/[^a-z0-9-]/g, "-");
  return {
    varName,
    import: `import ${varName} from "../blog-posts/${file}?raw";`,
    slug,
    path: `../blog-posts/${file}?raw`,
  };
});

// Generate the TypeScript file
const content = `// This file is auto-generated by scripts/generate-blog-imports.js
// Run: npm run generate-blog-imports

${imports.map((i) => i.import).join("\n")}

export const blogPostModules: Record<string, string> = {
${imports.map((i) => `  "${i.path}": ${i.varName},`).join("\n")}
};

export const blogPostSlugs: string[] = [
${imports.map((i) => `  "${i.slug}",`).join("\n")}
];
`;

writeFileSync(outputFile, content, "utf-8");
console.log(`Generated blog imports for ${files.length} files`);
console.log(`Output: ${outputFile}`);

